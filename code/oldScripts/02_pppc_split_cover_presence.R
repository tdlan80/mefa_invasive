# ==============================================================================
# Script: 02_pppc_split_cover_presence.R
# Purpose: Prepare two analytical datasets from NEON Plant Presence and
#          Percent Cover (DP1.10058.001), across the terrestrial sites
#          downloaded in 01_pppc_download_process_all_sites.R.
#
# Primary outputs:
#   1. pppc_1m_cover
#      Species-level percent cover in individual 1 m2 subplots.
#      Each row remains a NEON species observation; do not sum cover here.
#
#   2. pppc_400m_presence
#      One row per species per 20 x 20 m plot and sampling event.
#      Combine all 1, 10, and 100 m2 observations; presence only.
#      A completeness flag identifies plot-events with the expected number
#      of surveyed subplots at every scale.
#
# Supporting outputs:
#   pppc_plot_effort       - sampling-effort and completeness checks
#   pppc_1m_richness      - richness of each surveyed 1 m2 subplot
#   pppc_plot_richness    - mean 1 m2 and 400 m2 species richness
#
# Inputs (created by script 01):
#   rawData/NEON/PPPC/pppc_all_terrestrial_all_scales.RData
#   Objects: pppc_plantDiv and pppc_subplotVisits
#
# IMPORTANT: Sampling in 1 and 10 m2 subplots changed from 8 to 6 in 2019;
#            four 100 m2 subplots are expected for complete 400 m2 surveys.
#            From 2019 onward, larger subplots are generally surveyed every
#            other year. Missing larger-scale surveys are NOT zero richness.
# ============================================================================== 

library(dplyr)
library(here)

# ==============================================================================
# 1. Load the combined data generated by script 01
# ==============================================================================

pppc_dir <- here::here("rawData", "NEON", "PPPC")
input_file <- file.path(pppc_dir, "pppc_all_terrestrial_all_scales.RData")

if (!file.exists(input_file)) {
  stop("Cannot find processed NEON PPPC data. Run script 01 first: ", input_file)
}
load(input_file)

if (!exists("pppc_plantDiv") || !exists("pppc_subplotVisits")) {
  stop("Input file must contain pppc_plantDiv and pppc_subplotVisits.")
}

# These fields are needed to link taxa, sampling events, and plot effort.
required_plants <- c("siteID", "plotID", "eventID", "year", "subplotID",
                     "subplot_area_m2", "binomialName", "percentCover",
                     "nativeStatusCode")
required_visits <- c("siteID", "plotID", "eventID", "year", "subplotID",
                     "subplot_area_m2")

if (!all(required_plants %in% names(pppc_plantDiv))) {
  stop("Missing plant-data columns: ",
       paste(setdiff(required_plants, names(pppc_plantDiv)), collapse = ", "))
}
if (!all(required_visits %in% names(pppc_subplotVisits))) {
  stop("Missing subplot-visit columns: ",
       paste(setdiff(required_visits, names(pppc_subplotVisits)), collapse = ", "))
}

# Keys for a single 400 m2 plot during one NEON sampling event.
plot_keys <- c("siteID", "plotID", "eventID", "year")

# Physical plot identifier
plot_key = paste(siteID, plotID, sep = "_")

# Plot-specific sampling event
plot_event_key = paste(siteID, plotID, eventID, sep = "_")

# ==============================================================================
# 2. DATASET 1: Species-level percent cover in individual 1 m2 subplots
# ==============================================================================

# Species-specific percent cover is measured ONLY at the 1 m2 scale.
# Keep all original taxonomic fields and observation rows. In particular,
# do not calculate plot-level percent cover by adding records across subplots.
# Cover values can overlap vertically and are not necessarily additive to 100%.
#
# NOTE: Script 01 retained species, subspecies, and varieties only. Ground
# cover, genus-only identifications, and other omitted categories are NOT here.

pppc_1m_cover <- pppc_plantDiv %>%
  filter(subplot_area_m2 == 1L) %>%
  select(siteID, plotID, eventID, year, subplotID, binomialName,
         percentCover, everything())

# ==============================================================================
# 3. Check sampling completeness for each 20 x 20 m plot/event
# ==============================================================================

# Work from subplot-visit records, NOT species observations: subplots with no
# identified species must still count as surveyed. Script 01 already removed
# visits explicitly marked as sampling impractical.
#
# Counts are based on distinct subplot IDs, so multiple species observations
# in the same subplot cannot inflate sampling effort.

pppc_plot_effort <- pppc_subplotVisits %>%
  filter(!is.na(year), !is.na(subplotID),
         subplot_area_m2 %in% c(1L, 10L, 100L)) %>%
  group_by(across(all_of(plot_keys))) %>%
  summarise(
    n_1m2 = n_distinct(subplotID[subplot_area_m2 == 1L]),
    n_10m2 = n_distinct(subplotID[subplot_area_m2 == 10L]),
    n_100m2 = n_distinct(subplotID[subplot_area_m2 == 100L]),
    .groups = "drop"
  ) %>%
  mutate(
    # NEON changed the number of 1 and 10 m2 subplots in 2019.
    expected_small = if_else(year < 2019L, 8L, 6L),
    complete_1m2 = n_1m2 == expected_small,
    complete_400m2 = complete_1m2 &
      n_10m2 == expected_small & n_100m2 == 4L
  )

# IMPORTANT: 'complete_400m2' means the expected numbers of subplot IDs
# are present in the processed visit data. It cannot detect every historical
# field-protocol deviation, missing pre-2020 sampling flag, or taxonomic issue.

# ==============================================================================
# 4. DATASET 2: Presence-only species inventory for each 20 x 20 m plot
# ==============================================================================

# NEON 10 and 100 m2 tables chiefly list ADDITIONAL species that were not
# documented in nested smaller subplots. Thus combine ALL scales first, and
# count each species only once per plot/event.
#
# 'added_at_10m2' and 'added_at_100m2' show where the species was RECORDED.
# They are NOT statements that a species is absent from larger nested areas.
#
# Species are identified here by binomialName, as in script 01. Subspecies
# and varieties sharing a binomial are therefore counted as one species.

pppc_400m_presence <- pppc_plantDiv %>%
  filter(subplot_area_m2 %in% c(1L, 10L, 100L),
         !is.na(binomialName), binomialName != "") %>%
  group_by(across(all_of(plot_keys)), binomialName) %>%
  summarise(
    recorded_in_1m2 = any(subplot_area_m2 == 1L),
    added_at_10m2 = any(subplot_area_m2 == 10L),
    added_at_100m2 = any(subplot_area_m2 == 100L),
    # Flag conflicting native-status codes instead of choosing one.
    native_status_conflict = n_distinct(nativeStatusCode, na.rm = TRUE) > 1L,
    nativeStatusCode = {
      codes <- unique(na.omit(nativeStatusCode))
      if (length(codes) == 1L) codes else NA_character_
    },
    .groups = "drop"
  ) %>%
  mutate(presence = 1L) %>%
  left_join(
    pppc_plot_effort %>%
      select(all_of(plot_keys), complete_400m2),
    by = plot_keys
  ) %>%
  select(all_of(plot_keys), binomialName, presence, nativeStatusCode,
         native_status_conflict, recorded_in_1m2, added_at_10m2,
         added_at_100m2, complete_400m2)

# To analyze ONLY complete 400 m2 inventories, use:
# complete_species <- pppc_400m_presence %>% filter(complete_400m2)
# Do not interpret incomplete plot inventories as complete 400 m2 richness.

# ==============================================================================
# 5. Richness of each 1 m2 subplot (including zero detections)
# ==============================================================================

# Begin with the full set of surveyed 1 m2 subplots from script 01.
# Joining species counts onto this list preserves surveyed subplots with no
# qualifying species. These receive species richness = 0.
# NOTE: 0 means no SPECIES-LEVEL taxon in the processed data; genus-only
# records were previously excluded by script 01.

pppc_1m_richness <- pppc_subplotVisits %>%
  filter(subplot_area_m2 == 1L) %>%
  distinct(siteID, plotID, eventID, year, subplotID) %>%
  left_join(
    pppc_1m_cover %>%
      filter(!is.na(binomialName), binomialName != "") %>%
      group_by(across(all_of(c(plot_keys, "subplotID")))) %>%
      summarise(S_1m2 = n_distinct(binomialName), .groups = "drop"),
    by = c(plot_keys, "subplotID")
  ) %>%
  mutate(S_1m2 = coalesce(S_1m2, 0L))

# ==============================================================================
# 6. Optional plot-level richness summary (same plot/event units)
# ==============================================================================

mean_1m_richness <- pppc_1m_richness %>%
  group_by(across(all_of(plot_keys))) %>%
  summarise(mean_S_1m2 = mean(S_1m2), .groups = "drop")

# Species richness pooled over ALL scales: only report this as 400 m2
# richness when the expected 1, 10, and 100 m2 visits are present.
observed_plot_richness <- pppc_400m_presence %>%
  group_by(across(all_of(plot_keys))) %>%
  summarise(observed_S_all_scales = n_distinct(binomialName), .groups = "drop")

pppc_plot_richness <- pppc_plot_effort %>%
  left_join(mean_1m_richness, by = plot_keys) %>%
  left_join(observed_plot_richness, by = plot_keys) %>%
  mutate(
    # 0 is appropriate for plots with completed sampling and no detected
    # species-level taxa. NA is used when full sampling was not completed.
    observed_S_all_scales = coalesce(observed_S_all_scales, 0L),
    S_400m2 = if_else(complete_400m2,
                     observed_S_all_scales, NA_integer_)
  )

# ==============================================================================
# 7. Save separately so downstream scripts can load only what they need
# Save processed NEON Plant Presence and Percent Cover (PPPC) datasets
# ==============================================================================

# 1. Species-level percent cover in individual 1 m2 subplots.
#    Retains species identity, percent cover, plot/subplot IDs, and sampling
#    events. Used for species composition, cover, and invasion analyses.
saveRDS(pppc_1m_cover,
        file.path(pppc_dir, "pppc_1m_cover.rds"))


# 2. Cumulative species presence at the 400 m2 (20 x 20 m) plot scale.
#    Combines species detected across nested 1, 10, and 100 m2 subplots.
#    Each species is counted once per plot and sampling event.
#    Presence only; percent cover is not available at this scale.
saveRDS(pppc_400m_presence,
        file.path(pppc_dir, "pppc_400m_presence.rds"))


# 3. Sampling effort and completeness for each 400 m2 plot.
#    Records the number of surveyed subplots at each sampling scale
#    (1, 10, and 100 m2), with indicators of sampling completeness.
#    Used to identify plots with sufficient sampling for richness analyses.
saveRDS(pppc_plot_effort,
        file.path(pppc_dir, "pppc_plot_effort.rds"))


# 4. Species richness of individual 1 m2 subplots.
#    Counts unique species within each surveyed 1 m2 subplot.
#    Includes zero-richness subplots where sampling was completed.
#    Used to examine fine-scale richness and calculate plot-level means.
saveRDS(pppc_1m_richness,
        file.path(pppc_dir, "pppc_1m_richness.rds"))


# 5. Plot-level species richness summary (400 m2 plots).
#    Includes mean richness across 1 m2 subplots and cumulative richness
#    from the nested sampling scales, where available.
#    Retains site, plot, event, and sampling-completeness information.
#    Used for plot-level comparisons across sites and years.
saveRDS(pppc_plot_richness,
        file.path(pppc_dir, "pppc_plot_richness.rds"))

# ==============================================================================
# 8. Quality-control summary
# ==============================================================================

message("\n--- NEON PPPC processing summary ---")
message("1 m2 species-cover observations: ", nrow(pppc_1m_cover))
message("Unique 400 m2 plot/event/species records: ", nrow(pppc_400m_presence))
message("Plot/species records with conflicting native status: ",
        sum(pppc_400m_presence$native_status_conflict))
message("Plot-events assessed for sampling effort: ", nrow(pppc_plot_effort))
message("Plot-events meeting full subplot counts: ",
        sum(pppc_plot_effort$complete_400m2))
message("Incomplete plot-events: ",
        sum(!pppc_plot_effort$complete_400m2))

# Confirm sampling effort by year, and inspect incomplete plot-events.
print(pppc_plot_effort %>%
        count(year, complete_400m2, name = "n_plot_events"))

print(pppc_plot_effort %>%
        filter(!complete_400m2) %>%
        select(siteID, plotID, eventID, year, n_1m2, n_10m2, n_100m2) %>%
        head(15))

# Confirm no duplicated plot/event/species rows in the 400 m2 inventory.
stopifnot(!anyDuplicated(pppc_400m_presence[c(plot_keys, "binomialName")]))

